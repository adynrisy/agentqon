"""AgentQon — configuration (Phase 2).

Everything is environment-driven; secrets are read from the environment
only and never stored in the repo or the database.

  AGENTQON_DATABASE_URL   postgresql://user:pass@host:5432/db  (omit for SQLite dev mode)
  AGENTQON_DATA           local data dir for SQLite + artifacts (default ./data)

  MODEL CONNECTION (v20 — generation requires a real model; there is no
  offline/canned generation mode). A model is connected when any of these
  holds, in priority order: a tenant BYOK connection (⚙ Advanced →
  Connections), the env endpoint below, an OmniRoute sidecar answering on
  http://127.0.0.1:20128/v1, or a local Ollama answering on its default
  http://127.0.0.1:11434/v1 (auto-detected, zero config). See
  app/modelstate.py for the resolution rules.
  AGENTQON_LLM_BASE_URL   OpenAI-compatible base URL (default: local Ollama http://127.0.0.1:11434/v1)
  AGENTQON_LLM_API_KEY    provider key (default 'ollama' — local Ollama ignores it)
  AGENTQON_LLM_MODEL      model name (default qwen2.5:1.5b — the locally verified model;
                          larger models like qwen2.5:3b/7b drop in unchanged)
  AGENTQON_LLM_PRICE_IN   USD per 1M input tokens  (default 0 — local models)
  AGENTQON_LLM_PRICE_OUT  USD per 1M output tokens (default 0)
  AGENTQON_WORKER_MODE    inline | external (default inline: API drains the queue itself;
                          external: a separate `python -m app.worker` process does the work)
  AGENTQON_TELEGRAM_BOT_TOKEN      Telegram bot token (BotFather). Unset = the Telegram
                          front door (v16) is disabled; the app boots and serves
                          everything else unchanged.
  AGENTQON_TELEGRAM_WEBHOOK_SECRET secret_token registered with setWebhook; required
                          for the webhook to accept updates when a token is set.
  AGENTQON_TELEGRAM_BOT_USERNAME   bot username (no @) — only used to build the
                          t.me/<bot>?start=<code> deep link in the UI/API.
  AGENTQON_TELEGRAM_API_BASE       Bot API base (default https://api.telegram.org);
                          override to point the channel at a stub in tests.
  AGENTQON_WHATSAPP_TOKEN          Meta Cloud API access token. Unset (or no phone
                          number id) = the WhatsApp front door (v17) is disabled;
                          the app boots and serves everything else unchanged.
  AGENTQON_WHATSAPP_PHONE_NUMBER_ID  the Cloud API phone number id (the id from the
                          WhatsApp app settings, NOT the number itself).
  AGENTQON_WHATSAPP_VERIFY_TOKEN   your own webhook verify token (GET handshake).
  AGENTQON_WHATSAPP_APP_SECRET     Meta app secret. POST webhooks MUST
                          carry a valid X-Hub-Signature-256 (HMAC-SHA256
                          of the raw body) or they are refused — and
                          since v20.2 (Shield H4) the secret is
                          MANDATORY whenever the channel is enabled:
                          enabled-but-unsigned refuses every delivery
                          (fail closed, like Telegram).
  AGENTQON_WHATSAPP_API_BASE       Graph API base (default https://graph.facebook.com);
                          override to point the channel at a stub in tests.
  AGENTQON_WHATSAPP_API_VERSION    Graph API version (default v21.0).
  AGENTQON_WHATSAPP_BUSINESS_NUMBER  the business number, digits only with country
                          code (e.g. 15551234567) — only used to build the
                          wa.me/<number>?text=LINK%20<code> link in the UI/API.
  AGENTQON_WHATSAPP_TEMPLATE_NAME  utility template name for out-of-window result
                          alerts (body carries one parameter, {{1}} = the mission
                          title). Empty = out-of-window results are held and
                          delivered on the user's next message.
  AGENTQON_WHATSAPP_TEMPLATE_LANG  template language code (default en).
  AGENTQON_META_APP_ID             the Meta app's public App ID (v18 Embedded
                          Signup). Public value — the web UI's "Connect WhatsApp
                          with Facebook" button initialises the Facebook SDK
                          with it. Unset = one-click connect is not offered.
  AGENTQON_WHATSAPP_CONFIG_ID      the Facebook Login for Business CONFIGURATION
                          ID for the WhatsApp embedded-signup flow (created in
                          the Meta app console; public value, shown by
                          GET /v1/whatsapp/onboard/public-config).

  SHIELD (v20.2 — see ~/omnimind-shield/SHIELD_SPEC.md):
  AGENTQON_LOCAL_TOKEN    per-install local API token (generated by the
                          CLI at setup, stored 0600 in ~/.agentqon). When
                          set, every route except GET /health, the
                          webhook endpoints (own signature auth) and
                          GET /v1/auth/config requires it — presented as
                          the X-OmniMind-Local-Token header or proven by
                          a valid channel signature (below).
  AGENTQON_CHANNEL_SECRET per-install HMAC channel secret. The CLI signs
                          every request (X-OmniMind-Ts/-Nonce/-Sig over
                          method|path|ts|nonce|body-hash, +-120 s window,
                          nonce replay cache). A presented-but-invalid
                          signature is always refused — never a fallback.
  AGENTQON_PACKAGED       "1" when spawned by the packaged npm harness.
                          Packaged + dev auth + no local token = the
                          server refuses to start. Packaged also turns
                          on the exact Host allowlist and cross-site
                          Origin/Referer refusal.
  AGENTQON_BIND_HOST      the host the server is bound to (the CLI and
                          the Docker image declare it). Dev auth on a
                          non-loopback bind = the server refuses to
                          start (C2).
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path


def mirror_agentqon_env() -> None:
    """Rebrand bridge (AgentQon): AGENTQON_* is the preferred env prefix;
    OMNIMIND_* remains a legacy fallback so existing deployments keep
    working. Every AGENTQON_<X> present in the environment is mirrored
    onto OMNIMIND_<X>, which is what the read sites below (and in
    app/vault.py, app/library.py, app/agency.py, app/netpolicy.py) read.
    When both are set, AGENTQON_<X> wins; OMNIMIND_<X> alone is honoured
    unchanged."""
    for name, value in list(os.environ.items()):
        if name.startswith("AGENTQON_"):
            os.environ["OMNIMIND_" + name[len("AGENTQON_"):]] = value


mirror_agentqon_env()


@dataclass(frozen=True)
class Settings:
    database_url: str = ""           # "" -> SQLite under data_dir
    data_dir: Path = Path("data")
    # v20: whether the operator explicitly configured the env endpoint
    # (vs. the built-in Ollama default). Drives model-state resolution:
    # an explicit local endpoint is probed; auto-detection only runs
    # when the operator configured nothing. See app/modelstate.py.
    llm_base_url_explicit: bool = False
    llm_api_key_explicit: bool = False
    llm_base_url: str = "http://127.0.0.1:11434/v1"
    llm_api_key: str = "ollama"
    llm_model: str = "qwen2.5:1.5b"
    llm_price_in_per_m: float = 0.0
    llm_price_out_per_m: float = 0.0
    worker_mode: str = "inline"
    # ---- V3 (Master Build: routing, budget, admin) -----------------------
    # Conservative per-call reservation when a model's price is unknown:
    # the call must fit inside the mission cap via this reserve — unknown
    # is never treated as free.
    reserve_unknown_call_usd: float = 0.50
    # Admin endpoints (kill switch, platform overview) require this key in
    # the X-Admin-Key header. Empty = admin endpoints disabled.
    admin_key: str = ""
    # ---- Phase 4 (production hardening) ----------------------------------
    # Auth mode: "dev" = header identity (X-Tenant-Id / X-User-Id), local
    # development only. "accounts" = real users: email+password sessions
    # and/or OIDC bearer tokens, tenant membership + role required.
    auth_mode: str = "dev"
    oidc_issuer: str = ""            # e.g. https://your-idp.example/ (JWKS under it)
    oidc_client_id: str = ""         # expected audience (aud) of OIDC tokens
    session_ttl_hours: int = 168
    # Rate limits (fixed 60s windows, per key).
    rate_login_per_min: int = 5      # per email — brute-force brake
    rate_login_ip_per_min: int = 30  # per source IP (audit F12): the
    # per-email brake alone leaves password spraying across many
    # accounts from one source unbraked
    rate_run_per_min: int = 30       # mission runs + revisions per tenant
    rate_validate_per_min: int = 10  # connection validations per tenant
    # Vault master key may come from a file of Fernet keys (one per line,
    # version = line order) instead of env — the seam a KMS mounts into.
    vault_key_file: str = ""
    # ---- Phase 5 (live web research) --------------------------------------
    # live = agents research the real web through the Tool Gateway;
    # seed = Phase 1 demonstration corpus only. Live failures fall back
    # to the seed corpus with a visible ResearchFallback event.
    research_mode: str = "live"
    research_max_fetches: int = 5
    # ---- v21 (reach gateway pack) ---------------------------------------
    # Comma-separated reach channels enabled for the tool gateway
    # (web,rss,github,youtube,reddit,exa). Empty = every reach tool is
    # denied by the gateway as not_configured until the operator
    # enables its channel (AGENTQON_REACH_CHANNELS).
    reach_channels: str = ""
    # ---- v16 (Telegram front door) ---------------------------------------
    # All optional. telegram_bot_token empty = channel disabled. The
    # adapter reads these via load_settings() at call time (see
    # app/telegram.py channel_config) so tests can point the channel at a
    # stub API by setting the environment.
    telegram_bot_token: str = ""
    telegram_webhook_secret: str = ""
    telegram_bot_username: str = ""
    telegram_api_base: str = "https://api.telegram.org"
    # ---- v17 (WhatsApp front door, Meta Cloud API) -----------------------
    # All optional. Channel enabled = token AND phone_number_id present.
    # app_secret gates POST webhook authenticity (signature REQUIRED when
    # set); verify_token gates the GET subscription handshake.
    whatsapp_token: str = ""
    whatsapp_phone_number_id: str = ""
    whatsapp_verify_token: str = ""
    whatsapp_app_secret: str = ""
    whatsapp_api_base: str = "https://graph.facebook.com"
    whatsapp_api_version: str = "v21.0"
    whatsapp_business_number: str = ""
    whatsapp_template_name: str = ""
    whatsapp_template_lang: str = "en"
    # ---- v18 (WhatsApp self-serve onboarding, Embedded Signup) -----------
    # All optional. meta_app_id + whatsapp_config_id are PUBLIC values
    # (they ship to the browser); the exchange itself reuses
    # whatsapp_app_secret above as the app secret. Without them the
    # one-click connect button is replaced by an admin note and the
    # v17 manual path (env number + LINK codes) is the only route.
    meta_app_id: str = ""
    whatsapp_config_id: str = ""
    # ---- Shield (v20.2) ---------------------------------------------------
    # Per-install credentials the packaged CLI generates at setup and
    # passes via the environment at spawn (never argv). Empty = feature
    # off: repo-dev runs and hosted accounts deployments are unaffected
    # (hosted mode relies on session auth inside the same routes).
    local_token: str = ""
    channel_secret: str = ""
    packaged: bool = False           # spawned by the npm harness
    bind_host: str = ""              # declared bind host ("" = unknown)
    # ---- Free-roam (local mode) -------------------------------------------
    # The folder the harness was launched from, captured when settings
    # load: the server process's working directory, or AGENTQON_LAUNCH_DIR
    # when the CLI hands its own folder over at spawn (the packaged
    # server's working directory is its install tree, never the user's
    # project). In local mode an agent session created without a named
    # workspace adopts this folder as its home project. None = never
    # captured (direct Settings() construction, e.g. in unit tests).
    launch_dir: Path | None = None

    @property
    def use_postgres(self) -> bool:
        return self.database_url.startswith(("postgresql://", "postgres://"))

    @property
    def artifacts_dir(self) -> Path:
        return self.data_dir / "artifacts"

    @property
    def sqlite_path(self) -> Path:
        return self.data_dir / "omnimind.db"


def load_settings() -> Settings:
    mirror_agentqon_env()
    base = Path(__file__).resolve().parent.parent
    data_dir = Path(os.environ.get("OMNIMIND_DATA", base / "data"))
    return Settings(
        database_url=os.environ.get("OMNIMIND_DATABASE_URL", ""),
        data_dir=data_dir,
        llm_base_url_explicit="OMNIMIND_LLM_BASE_URL" in os.environ,
        llm_api_key_explicit="OMNIMIND_LLM_API_KEY" in os.environ,
        llm_base_url=os.environ.get("OMNIMIND_LLM_BASE_URL", "http://127.0.0.1:11434/v1"),
        llm_api_key=os.environ.get("OMNIMIND_LLM_API_KEY", "ollama"),
        llm_model=os.environ.get("OMNIMIND_LLM_MODEL", "qwen2.5:1.5b"),
        llm_price_in_per_m=float(os.environ.get("OMNIMIND_LLM_PRICE_IN", "0")),
        llm_price_out_per_m=float(os.environ.get("OMNIMIND_LLM_PRICE_OUT", "0")),
        worker_mode=os.environ.get("OMNIMIND_WORKER_MODE", "inline").lower(),
        reach_channels=os.environ.get("OMNIMIND_REACH_CHANNELS", ""),
        reserve_unknown_call_usd=float(os.environ.get("OMNIMIND_RESERVE_UNKNOWN_CALL_USD", "0.5")),
        admin_key=os.environ.get("OMNIMIND_ADMIN_KEY", ""),
        auth_mode=os.environ.get("OMNIMIND_AUTH_MODE", "dev").lower(),
        oidc_issuer=os.environ.get("OMNIMIND_OIDC_ISSUER", ""),
        oidc_client_id=os.environ.get("OMNIMIND_OIDC_CLIENT_ID", ""),
        session_ttl_hours=int(os.environ.get("OMNIMIND_SESSION_TTL_HOURS", "168")),
        rate_login_per_min=int(os.environ.get("OMNIMIND_RATE_LOGIN_PER_MIN", "5")),
        rate_login_ip_per_min=int(os.environ.get("OMNIMIND_RATE_LOGIN_IP_PER_MIN", "30")),
        rate_run_per_min=int(os.environ.get("OMNIMIND_RATE_RUN_PER_MIN", "30")),
        rate_validate_per_min=int(os.environ.get("OMNIMIND_RATE_VALIDATE_PER_MIN", "10")),
        vault_key_file=os.environ.get("OMNIMIND_VAULT_KEY_FILE", ""),
        research_mode=os.environ.get("OMNIMIND_RESEARCH_MODE", "live").lower(),
        research_max_fetches=int(os.environ.get("OMNIMIND_RESEARCH_MAX_FETCHES", "5")),
        telegram_bot_token=os.environ.get("OMNIMIND_TELEGRAM_BOT_TOKEN", ""),
        telegram_webhook_secret=os.environ.get("OMNIMIND_TELEGRAM_WEBHOOK_SECRET", ""),
        telegram_bot_username=os.environ.get("OMNIMIND_TELEGRAM_BOT_USERNAME", "").lstrip("@"),
        telegram_api_base=os.environ.get(
            "OMNIMIND_TELEGRAM_API_BASE", "https://api.telegram.org").rstrip("/"),
        whatsapp_token=os.environ.get("OMNIMIND_WHATSAPP_TOKEN", ""),
        whatsapp_phone_number_id=os.environ.get(
            "OMNIMIND_WHATSAPP_PHONE_NUMBER_ID", ""),
        whatsapp_verify_token=os.environ.get("OMNIMIND_WHATSAPP_VERIFY_TOKEN", ""),
        whatsapp_app_secret=os.environ.get("OMNIMIND_WHATSAPP_APP_SECRET", ""),
        whatsapp_api_base=os.environ.get(
            "OMNIMIND_WHATSAPP_API_BASE", "https://graph.facebook.com").rstrip("/"),
        whatsapp_api_version=os.environ.get(
            "OMNIMIND_WHATSAPP_API_VERSION", "v21.0").strip().lstrip("/"),
        whatsapp_business_number="".join(ch for ch in os.environ.get(
            "OMNIMIND_WHATSAPP_BUSINESS_NUMBER", "") if ch.isdigit()),
        whatsapp_template_name=os.environ.get("OMNIMIND_WHATSAPP_TEMPLATE_NAME", ""),
        whatsapp_template_lang=os.environ.get(
            "OMNIMIND_WHATSAPP_TEMPLATE_LANG", "en") or "en",
        meta_app_id=os.environ.get("OMNIMIND_META_APP_ID", ""),
        whatsapp_config_id=os.environ.get("OMNIMIND_WHATSAPP_CONFIG_ID", ""),
        local_token=os.environ.get("OMNIMIND_LOCAL_TOKEN", ""),
        channel_secret=os.environ.get("OMNIMIND_CHANNEL_SECRET", ""),
        packaged=os.environ.get("OMNIMIND_PACKAGED", "") == "1",
        bind_host=os.environ.get("OMNIMIND_BIND_HOST", ""),
        launch_dir=Path(os.environ.get("OMNIMIND_LAUNCH_DIR")
                        or Path.cwd()).resolve(),
    )
