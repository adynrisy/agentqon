"""AgentQon's own names for the agent roster and skill library.

Every agent and skill carries an original AgentQon display name
(app/data/display_names.json, keyed by the NEW ids) and a clean
AgentQon id (app/data/id_map.json maps every pre-rename id to
its replacement; app/data/id_by_body.json resolves a library
agent's new id from its persona body hash, because library
identity is content - the harvested file paths were renamed).

Generated by tools/build_display_names.py; applied to the tree
by tools/apply_tree_rename.py. Attribution metadata inside the
data files (repo, owner, license) is provenance and stays.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent / "data"


def _load(name: str) -> dict:
    try:
        return json.loads((DATA_DIR / name).read_text(encoding="utf-8"))
    except Exception:
        return {}


@lru_cache(maxsize=1)
def _display() -> dict:
    return _load("display_names.json")


@lru_cache(maxsize=1)
def _id_map() -> dict:
    return _load("id_map.json")


@lru_cache(maxsize=1)
def _by_body() -> dict:
    return _load("id_by_body.json")


def agent_display(agent_id: str) -> str | None:
    """The AgentQon display name for an agent id, if it has one."""
    if not agent_id:
        return None
    return (_display().get("agents") or {}).get(agent_id)


def skill_display(skill_id: str) -> str | None:
    if not skill_id:
        return None
    return (_display().get("skills") or {}).get(skill_id)


def new_agent_id(old_id: str) -> str | None:
    return (_id_map().get("agents") or {}).get(old_id)


def new_skill_id(old_id: str) -> str | None:
    return (_id_map().get("skills") or {}).get(old_id)


def agent_id_for_body(body_sha256: str) -> str | None:
    return _by_body().get(body_sha256)


def agent_id_map() -> dict[str, str]:
    return dict(_id_map().get("agents") or {})


def skill_id_map() -> dict[str, str]:
    return dict(_id_map().get("skills") or {})


def combined_id_map() -> dict[str, str]:
    out = agent_id_map()
    out.update(skill_id_map())
    return out
